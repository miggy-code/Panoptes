"""Install the panoptes Hermes plugin to ~/.hermes/plugins/panoptes/.

Usage:
    python -m panoptes.install_hermes_plugin
    python -m panoptes.install_hermes_plugin --dry-run
"""

import argparse
import os
import shutil
import sys
import tempfile
from pathlib import Path


MANIFEST_JSON = """{
    "name": "panoptes",
    "version": "0.1.0",
    "description": "Panoptes Hermes lifecycle observation and host-callable tool authorization",
    "hooks": ["agent:start", "agent:step", "agent:end"],
    "entrypoint": "plugin.py"
}"""

# The generated plugin.py is a thin entrypoint shim: the implementation lives
# in panoptes.hermes_plugin (the panoptes package must be importable in the
# Hermes environment either way, since the plugin writes to the panoptes DB).
# This keeps the hook logic in exactly one place.
PLUGIN_PY = '''"""Hermes plugin — panoptes lifecycle hooks.

Auto-generated by panoptes.install_hermes_plugin.
Captures agent:start, agent:step, and agent:end observations
to the local Panoptes audit database.

The implementation lives in the panoptes package; this file is just the
Hermes plugin entrypoint.
"""

from panoptes.hermes_plugin import AuditPlugin, get_plugin

plugin = get_plugin()

# Hosts with a synchronous pre-tool hook call this function and must decline
# execution when the returned decision has allowed=False. The lifecycle hooks
# below remain observation-only.
authorize_tool_call = plugin.authorize_tool_call
'''


def get_plugin_dir() -> Path:
    """Return the target plugin directory."""
    return Path.home() / ".hermes" / "plugins" / "panoptes"


def _atomic_private_write(path: Path, contents: str) -> None:
    """Replace one plugin file atomically with owner-only permissions."""
    if path.is_symlink():
        raise RuntimeError(f"Refusing to replace symlink plugin file: {path}")
    fd, temporary = tempfile.mkstemp(
        dir=str(path.parent),
        prefix=f".{path.name}.",
        text=True,
    )
    temporary_path = Path(temporary)
    try:
        if hasattr(os, "fchmod"):
            os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(contents)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary_path, path)
        path.chmod(0o600)
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        temporary_path.unlink(missing_ok=True)
        raise


def install(dry_run: bool = False) -> bool:
    """Install the plugin files to ~/.hermes/plugins/panoptes/.

    Args:
        dry_run: If True, print what would happen without writing files.

    Returns:
        True if successful.
    """
    plugin_dir = get_plugin_dir()

    if dry_run:
        print(f"[DRY RUN] Would create: {plugin_dir}/")
        print(f"[DRY RUN] Would write: {plugin_dir}/manifest.json")
        print(f"[DRY RUN] Would write: {plugin_dir}/plugin.py")
        return True

    if plugin_dir.is_symlink():
        raise RuntimeError(f"Refusing to install through symlink: {plugin_dir}")

    # Create directory
    plugin_dir.mkdir(parents=True, exist_ok=True)
    if not plugin_dir.is_dir():
        raise RuntimeError(f"Plugin path is not a directory: {plugin_dir}")
    plugin_dir.chmod(0o700)
    print(f"Created: {plugin_dir}/")

    manifest_path = plugin_dir / "manifest.json"
    plugin_path = plugin_dir / "plugin.py"
    for candidate in (manifest_path, plugin_path):
        if candidate.is_symlink():
            raise RuntimeError(
                f"Refusing to replace symlink plugin file: {candidate}"
            )

    # Write manifest.json
    _atomic_private_write(manifest_path, MANIFEST_JSON)
    print(f"Wrote: {manifest_path}")

    # Write plugin.py
    _atomic_private_write(plugin_path, PLUGIN_PY)
    print(f"Wrote: {plugin_path}")

    print("\n✅ panoptes Hermes plugin installed successfully!")
    print(f"   Location: {plugin_dir}")
    print("\n   The plugin will activate on next Hermes agent start.")
    print("   Audit events will be written to: ~/.panoptes/audit.db")

    return True


def uninstall(dry_run: bool = False) -> bool:
    """Remove the plugin files from ~/.hermes/plugins/panoptes/."""
    plugin_dir = get_plugin_dir()

    if not plugin_dir.exists():
        print(f"Plugin not installed (no directory at {plugin_dir}).")
        return True
    if plugin_dir.is_symlink():
        raise RuntimeError(f"Refusing to uninstall through symlink: {plugin_dir}")

    if dry_run:
        print(f"[DRY RUN] Would remove: {plugin_dir}/")
        return True

    shutil.rmtree(plugin_dir)
    print(f"Removed: {plugin_dir}/")
    print("✅ panoptes Hermes plugin uninstalled.")
    return True


def main():
    parser = argparse.ArgumentParser(
        description="Install or uninstall the panoptes Hermes plugin"
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be done without making changes",
    )
    parser.add_argument(
        "--uninstall",
        action="store_true",
        help="Remove the plugin instead of installing",
    )

    args = parser.parse_args()

    if args.uninstall:
        success = uninstall(dry_run=args.dry_run)
    else:
        success = install(dry_run=args.dry_run)

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
