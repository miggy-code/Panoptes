"""Install the panoptes Hermes plugin to ~/.hermes/plugins/panoptes/.

Usage:
    python -m panoptes.install_hermes_plugin
    python -m panoptes.install_hermes_plugin --dry-run
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path


MANIFEST_JSON = """{
    "name": "panoptes",
    "version": "0.1.0",
    "description": "Universal panoptes trail — captures every tool call and decision",
    "hooks": ["agent:start", "agent:step", "agent:end"],
    "entrypoint": "plugin.py"
}"""

PLUGIN_PY = '''"""Hermes plugin — panoptes lifecycle hooks.

Auto-generated by panoptes.install_hermes_plugin.
Captures agent:start, agent:step, and agent:end events
to the universal panoptes trail database.
"""

import datetime
import json
import os
import uuid

from panoptes.db import AuditDB

DB_PATH = os.path.expanduser("~/.panoptes/audit.db")


def _utcnow_iso():
    return datetime.datetime.now(datetime.timezone.utc).isoformat().replace("+00:00", "Z")


class AuditPlugin:
    """Hermes plugin that writes agent lifecycle events to the audit DB."""

    def __init__(self, db_path=None):
        self.db = AuditDB(db_path or DB_PATH)
        self._session_state = {}

    def register(self, ctx):
        @ctx.on("agent:start")
        def on_agent_start(context):
            session_id = context.get("session_id") or str(uuid.uuid4())
            run_id = context.get("run_id") or str(uuid.uuid4())
            user_id = context.get("user_id", "unknown")
            self._session_state = {
                "session_id": session_id,
                "run_id": run_id,
                "user_id": user_id,
                "turn": 0,
            }
            self.db.insert_event({
                "event_id": str(uuid.uuid4()),
                "timestamp": _utcnow_iso(),
                "agent": {"type": "hermes", "session_id": session_id, "run_id": run_id},
                "user": {"id": user_id, "auth_method": "cli"},
                "event_type": "model_request",
                "action": {"tool_name": None, "parameters": {}, "target": None},
                "outcome": {"status": "success", "summary": "Agent started processing"},
                "context": {"turn_number": 0, "user_message": context.get("message", "")[:500]},
                "cost": {"tokens_in": 0, "tokens_out": 0},
            })

        @ctx.on("agent:step")
        def on_agent_step(context):
            self._session_state["turn"] += 1
            tool_names = context.get("tool_names", [])
            for tool_name in tool_names:
                self.db.insert_event({
                    "event_id": str(uuid.uuid4()),
                    "timestamp": _utcnow_iso(),
                    "agent": {
                        "type": "hermes",
                        "session_id": self._session_state["session_id"],
                        "run_id": self._session_state.get("run_id"),
                    },
                    "event_type": "tool_call",
                    "action": {"tool_name": tool_name, "parameters": {}, "target": None},
                    "outcome": {"status": "success", "summary": f"Called {tool_name}"},
                    "context": {"turn_number": self._session_state["turn"]},
                    "cost": {},
                })

        @ctx.on("agent:end")
        def on_agent_end(context):
            self.db.insert_event({
                "event_id": str(uuid.uuid4()),
                "timestamp": _utcnow_iso(),
                "agent": {
                    "type": "hermes",
                    "session_id": self._session_state.get("session_id"),
                    "run_id": self._session_state.get("run_id"),
                },
                "event_type": "model_response",
                "action": {"tool_name": None, "parameters": {}, "target": None},
                "outcome": {"status": "success", "summary": context.get("response", "")[:200]},
                "context": {"turn_number": self._session_state.get("turn", 0)},
                "cost": {},
            })


plugin = AuditPlugin()
'''


def get_plugin_dir() -> Path:
    """Return the target plugin directory."""
    return Path.home() / ".hermes" / "plugins" / "panoptes"


def install(dry_run: bool = False) -> bool:
    """Install the plugin files to ~/.hermes/plugins/panoptes/.

    Args:
        dry_run: If True, print what would happen without writing files.

    Returns:
        True if successful.
    """
    plugin_dir = get_plugin_dir()

    if dry_run:
        print(f"[DRY RUN] Would create: {plugin_dir}/")
        print(f"[DRY RUN] Would write: {plugin_dir}/manifest.json")
        print(f"[DRY RUN] Would write: {plugin_dir}/plugin.py")
        return True

    # Create directory
    plugin_dir.mkdir(parents=True, exist_ok=True)
    print(f"Created: {plugin_dir}/")

    # Write manifest.json
    manifest_path = plugin_dir / "manifest.json"
    manifest_path.write_text(MANIFEST_JSON)
    print(f"Wrote: {manifest_path}")

    # Write plugin.py
    plugin_path = plugin_dir / "plugin.py"
    plugin_path.write_text(PLUGIN_PY)
    print(f"Wrote: {plugin_path}")

    print("\n✅ panoptes Hermes plugin installed successfully!")
    print(f"   Location: {plugin_dir}")
    print("\n   The plugin will activate on next Hermes agent start.")
    print("   Audit events will be written to: ~/.panoptes/audit.db")

    return True


def uninstall(dry_run: bool = False) -> bool:
    """Remove the plugin files from ~/.hermes/plugins/panoptes/."""
    plugin_dir = get_plugin_dir()

    if not plugin_dir.exists():
        print(f"Plugin not installed (no directory at {plugin_dir}).")
        return True

    if dry_run:
        print(f"[DRY RUN] Would remove: {plugin_dir}/")
        return True

    shutil.rmtree(plugin_dir)
    print(f"Removed: {plugin_dir}/")
    print("✅ panoptes Hermes plugin uninstalled.")
    return True


def main():
    parser = argparse.ArgumentParser(
        description="Install or uninstall the panoptes Hermes plugin"
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be done without making changes",
    )
    parser.add_argument(
        "--uninstall",
        action="store_true",
        help="Remove the plugin instead of installing",
    )

    args = parser.parse_args()

    if args.uninstall:
        success = uninstall(dry_run=args.dry_run)
    else:
        success = install(dry_run=args.dry_run)

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
